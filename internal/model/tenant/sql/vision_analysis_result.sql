CREATE TABLE vision_analysis_result (
    `id` BIGINT(20) UNSIGNED NOT NULL PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    `uuid` VARCHAR(64) NOT NULL COMMENT '资源UUID',
    `user_id` BIGINT(20) UNSIGNED NOT NULL COMMENT '用户ID',
    `type` VARCHAR(64) NOT NULL COMMENT '资源类型',
    `urls` JSON NOT NULL COMMENT '资源地址',
    `description` TEXT NOT NULL COMMENT '资源描述',
    `data` JSON NOT NULL COMMENT '资源提取数据',
    `result` JSON NOT NULL COMMENT '资源分析结果',
    `status` TINYINT(4) NOT NULL DEFAULT 0 COMMENT '状态',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) COMMENT '图片分析结果';